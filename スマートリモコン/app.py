# Automation scheduler (time-based trigger)
# ================================================================
_last_fired = {}   # auto_id -> "HH:MM" last fired date-time string to avoid double-fire

def _automation_scheduler():
    import datetime, time
    while True:
        now = datetime.datetime.now()
        hhmm = now.strftime("%H:%M")
        date_key = now.strftime("%Y-%m-%d")
        try:
            for auto in _read_automations():
                if not auto.get("enabled", True):
                    continue
                trigger = auto.get("trigger", {})
                if trigger.get("type") != "time":
                    continue
                if trigger.get("time") != hhmm:
                    continue
                fire_key = f"{auto['id']}_{date_key}_{hhmm}"
                if _last_fired.get(auto["id"]) == fire_key:
                    continue
                _last_fired[auto["id"]] = fire_key
                # Run actions in background
                def _execute(a=auto):
                    import time as _time
                    delay_s = a.get("delay_ms", 1000) / 1000.0
                    for act in a.get("actions", []):
                        key = f"{act['device']}:{act['action']}"
                        codes = _read_codes()
                        if key in codes:
                            try:
                                _set_mos_gpio(act['device'])
                                subprocess.run(
                                    ["python3", IRRP_PATH, "-p", f"-g{GPIO_SEND}", "-f", CODES_FILE, key],
                                    capture_output=True, text=True, timeout=10
                                )
                                _mos_off()
                            except Exception as e:
                                _mos_off()
                                print(f"[SCHED SEND ERROR] key={key!r} error={e}", flush=True)
                        _time.sleep(delay_s)
                threading.Thread(target=_execute, daemon=True).start()
        except Exception:
            pass
        time.sleep(30)  # check every 30 seconds

threading.Thread(target=_automation_scheduler, daemon=True).start()


