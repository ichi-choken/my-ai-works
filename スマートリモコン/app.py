@app.route("/api/automations/<auto_id>/run", methods=["POST"])
def run_automation(auto_id):
    automations = _read_automations()
    auto = next((a for a in automations if a["id"] == auto_id), None)
    if not auto:
        return jsonify({"ok": False, "error": "not found"}), 404
    def _execute():
        import time
        delay_s = auto.get("delay_ms", 1000) / 1000.0
        for act in auto.get("actions", []):
            key = f"{act['device']}:{act['action']}"
            codes = _read_codes()
            if key in codes:
                try:
                    _set_mos_gpio(act['device'])
                    subprocess.run(
                        ["python3", IRRP_PATH, "-p", f"-g{GPIO_SEND}", "-f", CODES_FILE, key],
                        capture_output=True, text=True, timeout=10
                    )
                    _mos_off()
                except Exception as e:
                    _mos_off()
                    print(f"[AUTO SEND ERROR] key={key!r} error={e}", flush=True)
            time.sleep(delay_s)
    threading.Thread(target=_execute, daemon=True).start()
    return jsonify({"ok": True})


