def _set_mos_gpio(device_id: str):
    """
    デバイス ID に応じて MOS FET 制御 GPIO を排他的に切り替える。
    - MOS22_DEVICE_IDS に含まれる場合: GPIO22=HIGH / GPIO27=LOW / GPIO23=LOW
    - MOS23_DEVICE_IDS に含まれる場合: GPIO23=HIGH / GPIO22=LOW / GPIO27=LOW
    - それ以外:                        GPIO27=HIGH / GPIO22=LOW / GPIO23=LOW
    """
    try:
        pi = _get_pi_mos()
        if not pi.connected:
            print("[MOS SET ERROR] pigpio not connected", flush=True)
            return
        if device_id in MOS22_DEVICE_IDS:
            pi.write(GPIO_MOS_27, 0)
            pi.write(GPIO_MOS_23, 0)
            pi.write(GPIO_MOS_22, 1)
            print(f"[MOS] GPIO22=HIGH / GPIO27=LOW / GPIO23=LOW  (device={device_id!r})", flush=True)
        elif device_id in MOS23_DEVICE_IDS:
            pi.write(GPIO_MOS_22, 0)
            pi.write(GPIO_MOS_27, 0)
            pi.write(GPIO_MOS_23, 1)
            print(f"[MOS] GPIO23=HIGH / GPIO22=LOW / GPIO27=LOW  (device={device_id!r})", flush=True)
        else:
            pi.write(GPIO_MOS_22, 0)
            pi.write(GPIO_MOS_23, 0)
            pi.write(GPIO_MOS_27, 1)
            print(f"[MOS] GPIO27=HIGH / GPIO22=LOW / GPIO23=LOW  (device={device_id!r})", flush=True)
    except Exception as e:
        print(f"[MOS SET ERROR] {e}", flush=True)


def _mos_off():
    """IR 送信完了後に全 MOS FET GPIO を LOW（オフ）に戻す"""
    try:
        pi = _get_pi_mos()
        if not pi.connected:
            return
        pi.write(GPIO_MOS_22, 0)
        pi.write(GPIO_MOS_27, 0)
        pi.write(GPIO_MOS_23, 0)
        print("[MOS] GPIO22=LOW / GPIO27=LOW / GPIO23=LOW  (送信完了後オフ)", flush=True)
    except Exception as e:
        print(f"[MOS OFF ERROR] {e}", flush=True)


def _init_gpio():
    """起動時に GPIO_SEND / MOS FET GPIO を LOW に初期化する"""
    try:
        pi = _get_pi_mos()
        if not pi.connected:
            print("[GPIO INIT] pigpio not connected", flush=True)
            return
        pi.set_mode(GPIO_SEND, pigpio.OUTPUT)
        pi.write(GPIO_SEND,   0)
        pi.write(GPIO_MOS_22, 0)
        pi.write(GPIO_MOS_27, 0)
        pi.write(GPIO_MOS_23, 0)
    except Exception as e:
        print(f"[GPIO INIT] {e}", flush=True)

_init_gpio()

