def _carrier(gpio, frequency, micros):
    """irrp.py と同じ 38kHz キャリアバースト生成"""
    cycle = 1000.0 / frequency        # μs per cycle (38kHz → 26.3μs)
    cycles = int(round(micros / cycle))
    on  = int(round(cycle / 2.0))
    off = int(round(cycle - on))
    wf = []
    for _ in range(cycles):
        wf.append(pigpio.pulse(1 << gpio, 0,         on))
        wf.append(pigpio.pulse(0,         1 << gpio, off))
    return wf


def _send_ir_direct(key: str) -> tuple[bool, str]:
    """
    38kHz キャリアバーストで IR 信号を送信する。

    pigpio には2つの上限があり、素直に実装するとどちらかに必ず当たる。
      - chain が長すぎる      → 'chain is too long'
      - DMA 制御ブロック枯渇  → 'No more CBs for waveform'
    そこで (mark, space) のペア単位で波形を作り、同じ組み合わせは
    1つの波形を使い回す。IR信号は数種類のペアの繰り返しなので、
    実際に作られる波形は数個で済み、CB 消費が桁違いに小さくなる。
    chain の要素数はペア数（= パルス数の半分）になる。
    """
    import time
    codes = _read_codes()
    if key not in codes:
        return False, "code not found"

    pulses_us = codes[key]
    if not pulses_us:
        return False, "empty pulse list"

    MAX_CHAIN = 450   # chain 要素数の安全上限
    MAX_WAVES = 200   # 同時に作る波形数の安全上限

    # 1) [mark, space, mark, space, ...] を (mark, space) のペア列にする
    pairs = []
    for i in range(0, len(pulses_us), 2):
        mark  = int(pulses_us[i])
        space = int(pulses_us[i + 1]) if i + 1 < len(pulses_us) else 0
        if mark <= 0 and space <= 0:
            continue
        pairs.append((mark, space))
    if not pairs:
        return False, "empty pulse list"

    # 2) chain が上限を超えるならペアをまとめて1波形にする
    group = 1
    while (len(pairs) + group - 1) // group > MAX_CHAIN:
        group += 1
    groups = [tuple(pairs[i:i + group]) for i in range(0, len(pairs), group)]

    pi = None
    cache = {}   # グループ内容 -> wave id
    try:
        pi = pigpio.pi()
        if not pi.connected:
            return False, "pigpio not connected"

        pi.set_mode(GPIO_SEND, pigpio.OUTPUT)
        pi.wave_clear()

        chain = []
        for grp in groups:
            wid = cache.get(grp)
            if wid is None:
                wf = []
                for mark, space in grp:
                    if mark > 0:
                        wf.extend(_carrier(GPIO_SEND, 38.0, mark))
                    if space > 0:
                        wf.append(pigpio.pulse(0, 1 << GPIO_SEND, space))
                if not wf:
                    continue
                pi.wave_add_new()
                pi.wave_add_generic(wf)
                wid = pi.wave_create()
                if wid < 0:
                    return False, f"wave_create failed (id={wid})"
                cache[grp] = wid
                if len(cache) > MAX_WAVES:
                    return False, f"too many waveforms ({len(cache)})"
            chain.append(wid)

        if not chain:
            return False, "empty waveform"

        print(f"[IR DIRECT] key={key!r} pulses={len(pulses_us)} "
              f"chain={len(chain)} waves={len(cache)} group={group}", flush=True)

        pi.wave_chain(chain)

        deadline = time.time() + 10.0
        while pi.wave_tx_busy():
            if time.time() > deadline:
                pi.wave_tx_stop()
                return False, "wave send timeout"
            time.sleep(0.005)

        time.sleep(POST_MS / 1000.0)
        return True, ""

    except Exception as e:
        return False, str(e)
    finally:
        if pi is not None:
            try:
                for wid in cache.values():
                    pi.wave_delete(wid)
                pi.write(GPIO_SEND, 0)
            except Exception:
                pass
            pi.stop()


@app.route("/api/send", methods=["POST"])
def send_code():
    data   = request.get_json(force=True) or {}
    dev_id = data.get("device", "").strip()
    action = data.get("action", "").strip()
    key    = f"{dev_id}:{action}"
    if not dev_id or not action:
        return jsonify({"ok": False, "error": "device and action required"}), 400
    if key not in _read_codes():
        return jsonify({"ok": False, "error": "code not found"}), 404

    try:
        _set_mos_gpio(dev_id)
        pi = _get_pi_mos()
        print(f"[MOS CHECK] before send: GPIO22={pi.read(GPIO_MOS_22)} GPIO27={pi.read(GPIO_MOS_27)} GPIO23={pi.read(GPIO_MOS_23)}", flush=True)
        ok, err = _send_ir_direct(key)
        print(f"[MOS CHECK] after send:  GPIO22={pi.read(GPIO_MOS_22)} GPIO27={pi.read(GPIO_MOS_27)} GPIO23={pi.read(GPIO_MOS_23)}", flush=True)
        _mos_off()
        if not ok:
            print(f"[IR SEND ERROR] key={key!r} err={err!r}", flush=True)
            return jsonify({"ok": False, "error": err or "send failed"}), 500
        print(f"[IR SEND OK] key={key!r}", flush=True)
        return jsonify({"ok": True})
    except subprocess.TimeoutExpired:
        _mos_off()
        return jsonify({"ok": False, "error": "timeout"}), 500

@app.route("/api/devices/<dev_id>/codes/<action>", methods=["DELETE"])
def delete_code(dev_id, action):
    key   = f"{dev_id}:{action}"
    codes = _read_codes()
    if key not in codes:
        return jsonify({"ok": False, "error": "not found"}), 404
    del codes[key]
    _write_codes(codes)
    labels = _read_labels()
    if labels.pop(key, None) is not None:
        _write_labels(labels)
    return jsonify({"ok": True})

@app.route("/api/devices/<dev_id>/codes/<action>/rename", methods=["POST"])
def rename_code(dev_id, action):
    data       = request.get_json(force=True) or {}
    new_action = (data.get("name") or "").strip()
    new_label  = data.get("label")
    old_key    = f"{dev_id}:{action}"
    codes      = _read_codes()
    if old_key not in codes:
        return jsonify({"ok": False, "error": "not found"}), 404

    # 表示名だけの変更（コードキーは据え置き）
    if not new_action:
        if new_label is None:
            return jsonify({"ok": False, "error": "name required"}), 400
        _set_label(old_key, new_label)
        return jsonify({"ok": True})

    new_key = f"{dev_id}:{new_action}"
    if new_key != old_key:
        if new_key in codes:
            return jsonify({"ok": False, "error": "name already exists"}), 409
        codes[new_key] = codes.pop(old_key)
        _write_codes(codes)
        labels = _read_labels()
        if old_key in labels:
            labels[new_key] = labels.pop(old_key)
            _write_labels(labels)

    if new_label is not None:
        _set_label(new_key, new_label)
    return jsonify({"ok": True})


