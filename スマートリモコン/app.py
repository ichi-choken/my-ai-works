AUTOMATIONS_FILE = os.path.join(os.path.dirname(__file__), "automations.json")

def _read_automations() -> list:
    if not os.path.exists(AUTOMATIONS_FILE):
        return []
    try:
        with open(AUTOMATIONS_FILE) as f:
            return json.load(f)
    except Exception:
        return []

def _write_automations(automations: list):
    with open(AUTOMATIONS_FILE, "w") as f:
        json.dump(automations, f, ensure_ascii=False, indent=2)

@app.route("/api/automations", methods=["GET"])
def list_automations():
    return jsonify(_read_automations())

@app.route("/api/automations", methods=["POST"])
def create_automation():
    data = request.get_json(force=True) or {}
    import uuid, datetime
    auto_id  = str(uuid.uuid4())[:8]
    name     = data.get("name", "").strip()
    trigger  = data.get("trigger", {})   # {"type": "time", "time": "23:45"}
    actions  = data.get("actions", [])   # [{"device": "tv", "action": "power_off"}, ...]
    enabled  = data.get("enabled", True)
    delay_ms = int(data.get("delay_ms", 1000))  # delay between each action in ms
    if not name:
        return jsonify({"ok": False, "error": "name required"}), 400
    if not actions:
        return jsonify({"ok": False, "error": "actions required"}), 400
    automation = {
        "id": auto_id,
        "name": name,
        "trigger": trigger,
        "actions": actions,
        "enabled": enabled,
        "delay_ms": delay_ms,
        "created_at": datetime.datetime.now().isoformat()
    }
    automations = _read_automations()
    automations.append(automation)
    _write_automations(automations)
    return jsonify({"ok": True, "id": auto_id})

@app.route("/api/automations/<auto_id>", methods=["PUT"])
def update_automation(auto_id):
    data = request.get_json(force=True) or {}
    automations = _read_automations()
    auto = next((a for a in automations if a["id"] == auto_id), None)
    if not auto:
        return jsonify({"ok": False, "error": "not found"}), 404
    if "name"     in data: auto["name"]     = data["name"].strip()
    if "trigger"  in data: auto["trigger"]  = data["trigger"]
    if "actions"  in data: auto["actions"]  = data["actions"]
    if "enabled"  in data: auto["enabled"]  = data["enabled"]
    if "delay_ms" in data: auto["delay_ms"] = int(data["delay_ms"])
    _write_automations(automations)
    return jsonify({"ok": True})

