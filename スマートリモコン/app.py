@app.route("/api/devices", methods=["POST"])
def add_device():
    data = request.get_json(force=True) or {}
    dev_id   = data.get("id", "").strip()
    name     = data.get("name", "").strip()
    category = data.get("category", "その他").strip()
    icon     = data.get("icon", "device").strip()
    if not dev_id or not name:
        return jsonify({"ok": False, "error": "id and name required"}), 400
    devices = _read_devices()
    if any(d["id"] == dev_id for d in devices):
        return jsonify({"ok": False, "error": "id already exists"}), 409
    devices.append({"id": dev_id, "name": name, "category": category, "icon": icon})
    _write_devices(devices)
    return jsonify({"ok": True})

@app.route("/api/devices/<dev_id>", methods=["PUT"])
def update_device(dev_id):
    data = request.get_json(force=True) or {}
    devices = _read_devices()
    dev = next((d for d in devices if d["id"] == dev_id), None)
    if not dev:
        return jsonify({"ok": False, "error": "not found"}), 404
    dev["name"]     = data.get("name", dev["name"]).strip()
    dev["category"] = data.get("category", dev["category"]).strip()
    dev["icon"]     = data.get("icon", dev["icon"]).strip()
    _write_devices(devices)
    return jsonify({"ok": True})

@app.route("/api/devices/reorder", methods=["POST"])
def reorder_devices():
    """デバイスの並び順を保存する。body: {"order": ["tv", "aircon", ...]}"""
    data  = request.get_json(force=True) or {}
    order = data.get("order")
    if not isinstance(order, list):
        return jsonify({"ok": False, "error": "order must be a list"}), 400
    devices = _read_devices()
    by_id   = {d["id"]: d for d in devices}
    # order に含まれるものを先頭に、含まれないものは元の順で末尾に残す
    new_list = [by_id[i] for i in order if i in by_id]
    new_list += [d for d in devices if d["id"] not in order]
    _write_devices(new_list)
    return jsonify({"ok": True})

@app.route("/api/devices/<dev_id>", methods=["DELETE"])
def delete_device(dev_id):
    devices = _read_devices()
    if not any(d["id"] == dev_id for d in devices):
        return jsonify({"ok": False, "error": "not found"}), 404
    devices = [d for d in devices if d["id"] != dev_id]
    _write_devices(devices)
    # デバイスに紐づくコードも削除
    prefix = f"{dev_id}:"
    codes  = {k: v for k, v in _read_codes().items() if not k.startswith(prefix)}
    _write_codes(codes)
    return jsonify({"ok": True})


