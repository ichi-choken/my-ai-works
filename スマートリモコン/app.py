# MOS GPIO 制御用 pigpio インスタンス（アプリ全体で使い回す）
_pi_mos = None

def _get_pi_mos():
    global _pi_mos
    if _pi_mos is None or not _pi_mos.connected:
        _pi_mos = pigpio.pi()
        if _pi_mos.connected:
            _pi_mos.set_mode(GPIO_MOS_22, pigpio.OUTPUT)
            _pi_mos.set_mode(GPIO_MOS_27, pigpio.OUTPUT)
            _pi_mos.set_mode(GPIO_MOS_23, pigpio.OUTPUT)
    return _pi_mos

